"""Spektra AI's protobuf -> .spektra mappers give what SpektraPlus's own mappers give.

tests/fixtures/parity_expected.json holds protobuf messages (empty, filled, max) and
what SpektraPlus's own mappers returned for each, generated by running SpektraPlus
(tools/spektraplus_parity/). This is what found NO_COMMAND triggers read as
DALI arcs and unprogrammed DALI lines read as 0. Regenerate when SpektraPlus changes.
"""
import base64
import json
from pathlib import Path

import edidio_control_py.eDS10_ProtocolBuffer_pb2 as pb
import pytest

from edidio_spektra_ai import spektra_map as M

CASES = json.loads((Path(__file__).parent / "fixtures" / "parity_expected.json")
                   .read_text(encoding="utf-8"))

PY = {"mapPbTriggerToEdidioTrigger": M.trigger_to_dict,
      "mapPbAlarmToEdidioSchedule": M.schedule_to_dict,
      "mapPbSequenceToEdidioSequenceData": M.sequence_to_dict,
      "mapPbThemeToEdidioThemeData": M.theme_to_dict,
      "mapPbInputToEdidioInput": M.input_to_dict,
      "mapPbOutputToEdidioOutput": M.output_to_dict,
      "mapPbLogicToEdidioLogicAction": M.logic_to_dict,
      "mapPbSensorToEdidioSensor": M.sensor_to_dict,
      "mapPbDaliInputToEdidioDALIInput": M.daliinput_to_dict,
      "mapPbSpektraSettingsToEdidioZone": M.zone_to_dict,
      "mapPbTranslationToEdidioControlTranslation": M.translation_to_dict,
      "mapPbBurnInToEdidioBurnIn": M.burnin_to_dict}

RANDOM_KEYS = {"uuid", "identifier"}          # render keys, new on every read
# Known, explained differences: (mapper, mode, path) -> why.
ALLOWED = {
    ("mapPbSpektraSettingsToEdidioZone", "empty", ".scaleFactor"):
        "the firmware stores a factor below its minimum, 0 included, as 1.0, "
        "so 0 never comes from a controller; see spektra_map",
}


def differences(a, b, path=""):
    out = []
    if isinstance(a, dict) and isinstance(b, dict):
        for k in sorted(set(a) | set(b)):
            if k in RANDOM_KEYS:
                continue
            if k not in a or k not in b:
                out.append(f"{path}.{k}: {'only in Spektra AI' if k not in a else 'missing in Spektra AI'}")
            else:
                out += differences(a[k], b[k], f"{path}.{k}")
    elif isinstance(a, list) and isinstance(b, list) and len(a) == len(b):
        for i, (x, y) in enumerate(zip(a, b)):
            out += differences(x, y, f"{path}[{i}]")
    elif a != b and not (isinstance(a, (int, float)) and isinstance(b, (int, float))
                         and abs(a - b) < 1e-6):
        out.append(path)
    return out


@pytest.mark.parametrize("case", CASES, ids=[f"{c['mapper'][5:]}-{c['mode']}" for c in CASES])
def test_same_result_as_spektraplus(case):
    assert "error" not in case, f"SpektraPlus could not map this case: {case.get('error')}"
    msg = getattr(pb, case["message"])()
    msg.ParseFromString(base64.b64decode(case["bytes"]))
    fn = PY[case["mapper"]]
    got = fn(msg) if case["index"] is None else fn(msg, case["index"])
    got = json.loads(json.dumps(got, default=str))
    diff = [p for p in differences(case["expected"], got)
            if (case["mapper"], case["mode"], p) not in ALLOWED]
    assert not diff, f"differs from SpektraPlus at {diff}"


def test_every_mapper_is_covered():
    assert {c["mapper"] for c in CASES} == set(PY)
